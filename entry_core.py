# 費用の目安（仮置き・円）。学校の見積もりで書きかえる
COST = {"流通・物流": 0, "農業": 30_000, "食品加工": 10_000, "ものづくり": 80_000}
COST_IF_HAVE = {"ものづくり": {"3Dプリンター": 70_000}}  # これがあれば差し引く額


def start_order(have: Sequence[str], school: str) -> list[dict]:
    """いまあるものから、始めやすい分野の順を出す。足りないもの・費用の目安つき。

    並べ方：足りないものの数 → 費用 → 学校種の定番順（通信制は物流から、特別支援は食品加工から）。
    """
    have = set(have)
    base = (["流通・物流", "農業", "食品加工", "ものづくり"] if school == SCHOOLS[1]
            else ["食品加工", "流通・物流", "農業", "ものづくり"])
    rows = []
    for f in FIELDS:
        lack = [n for n in NEEDS[f] if n not in have]
        cost = COST[f] - sum(v for k, v in COST_IF_HAVE.get(f, {}).items() if k in have)
        note = []
        if f == "食品加工" and "保健所に相談できる担当" not in have:
            note.append("販売するなら保健所への相談が先")
        if "地域企業とのつながり" not in have:
            note.append("外部評価の相手（企業・農家）を1件探す")
        rows.append({"分野": f, "足りないもの": lack, "費用の目安": max(cost, 0), "メモ": note})
    rows.sort(key=lambda r: (len(r["足りないもの"]), r["費用の目安"], base.index(r["分野"])))
    for i, r in enumerate(rows, start=1):
        r["順"] = i
    return rows


