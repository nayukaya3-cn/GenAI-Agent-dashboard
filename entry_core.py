def manual_prompt(field: str, task: str, steps: Sequence[str], school: str, furigana: bool = True) -> str:
    """生成AIに貼る「手順書づくり」の質問文（この画面は生成AIを呼び出さない。利用者が自分で貼る）"""
    lines = [s.strip() for s in steps if s.strip()]
    if not task.strip() or not lines:
        raise ValueError("作業名と、工程を1つ以上入れてください")
    who = ("特別支援学校高等部の生徒" if school == SCHOOLS[0] else "通信制高校・サポート校の生徒（作業に慣れていない人を含む）")
    numbered = "\n".join(f"{i}. {s}" for i, s in enumerate(lines, start=1))
    form = "ふりがな（漢字の後に（ ）で）をつけ、" if furigana else ""
    return (f"【目的】{who}が、{field}の作業「{task}」を一人で進められる手順書を作りたい。\n"
            f"【いまの工程】\n{numbered}\n"
            f"【ルール】1工程1行、1行は20字以内。{form}やさしい日本語で書く。数字・色・位置で具体的に示す。"
            "否定（〜しない）より、するべき動作で書く。安全・衛生の確認は独立した工程にする。\n"
            "【形式】番号付きの手順、各工程に「写真に写すもの」と「できた／支援ありでできた／まだ」の評価欄をつける表。\n"
            "【確認】工程を勝手に増やしたり減らしたりした所があれば、最後に一覧で示す。\n"
            "※生徒の氏名・診断名・支援記録は入れていません。")


def step_probability(success: int, attempts: int, prior: tuple[float, float] = (1.0, 1.0),
                     draws: int = 20_000, seed: int = 0) -> dict[str, float]:
    """評価表の記録（この工程を何回中何回できたか）から、「この工程ができる確率」をベイズ推定する。

    ベータ分布の事前分布（初期値は一様）を、できた回数・できなかった回数で更新する。
    """
    if attempts < 0 or not 0 <= success <= attempts:
        raise ValueError("できた回数は 0 以上、記録した回数以下にしてください")
    a, b = prior[0] + success, prior[1] + attempts - success
    s = np.random.default_rng(seed).beta(a, b, draws)
    return {"平均": a / (a + b), "下": float(np.quantile(s, 0.1)), "上": float(np.quantile(s, 0.9)),
            "8割を超える確率": float((s > 0.8).mean())}


