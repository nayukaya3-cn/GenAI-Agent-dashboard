def funnel(reach: float, rates: Sequence[float]) -> list[float]:
    """段ごとの人数。rates は 2段目以降の「前の段からの割合」"""
    out = [float(reach)]
    for r in rates:
        out.append(out[-1] * float(r))
    return out


def fan_curve(new_per_year: float, retention: float, years: int = 5, start: float = 0) -> list[float]:
    """定期便の会員数：毎年 retention の割合が続け、new_per_year 人が新しく入る。行き着く先は new/(1−retention)"""
    f, out = float(start), []
    for _ in range(years):
        f = f * retention + new_per_year
        out.append(f)
    return out


def ltv(spend_per_year: float, retention: float) -> float:
    """1人が続けてくれる年数の期待値は 1/(1−retention)。その間の支出の合計"""
    return spend_per_year / max(1e-9, 1 - retention)


def mvp_judge(invited: int, bought: int, need_rate: float, draws: int = 20_000, seed: int = 0) -> dict[str, float]:
    """テスト販売：invited 人に案内し bought 人が買った。買う割合を Beta(1+買った, 1+買わない) で表し、
    損益分岐の割合 need_rate を上回る確率を返す"""
    n, b = max(0, int(invited)), max(0, int(bought))
    b = min(b, n)
    xs = np.random.default_rng(seed).beta(1 + b, 1 + n - b, draws)
    return {"平均": (b + 1) / (n + 2), "下": float(np.quantile(xs, 0.1)), "上": float(np.quantile(xs, 0.9)),
            "分岐を超える確率": float((xs > need_rate).mean())}


