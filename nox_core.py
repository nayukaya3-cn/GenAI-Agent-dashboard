def teach_months(audience: str) -> list[dict]:
    """月ごとに、その月に扱える農の工程と、授業のある週数"""
    col = 1 if AUDIENCE[audience][0].startswith("作業") else 2
    out = []
    for m in range(1, 13):
        rows = [t for t in TEACH if m in t[4]]
        out.append({"月": f"{m}月", "授業の週": TERM_WEEKS[m - 1], "扱える工程": "・".join(t[0] for t in rows) or "―",
                    "中身": "／".join(t[col] for t in rows) or "―"})
    return out


