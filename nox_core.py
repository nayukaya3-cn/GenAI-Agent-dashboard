def simulate_income(streams: Sequence[tuple], fixed_cost: float = 300_000, sigma: float = 0.25, p_bad: float = 0.1,
                    bad_yield: float = 0.4, n: int = 10_000, seed: int = 0) -> np.ndarray:
    """1年の手取り（売上−原価−固定費）を n 年分ためしに引く。
    天候：その年の共通の良し悪し Z と、品目ごとのぶれ。ときどき大きな不作（確率 p_bad、収量 bad_yield 倍）。
    天候の効き w の品目だけが影響を受ける。成り立つ確率 p で、その品目が1年まるごと成り立つかが決まる（契約・集客）。"""
    rng = np.random.default_rng(seed)
    z = rng.standard_normal(n)
    bad = rng.random(n) < p_bad
    total = np.full(n, -float(fixed_cost))
    for _, _, qty, price, cost, w, p in streams:
        w = float(w)
        mult = 1 + w * (sigma * z + 0.1 * rng.standard_normal(n))
        mult = np.where(bad, mult * (1 - w * (1 - bad_yield)), mult)
        ok = rng.random(n) < float(p)
        total += np.clip(mult, 0, None) * ok * float(qty) * float(price) * (1 - float(cost))
    return total


def income_summary(sim: np.ndarray, target: float) -> dict[str, float]:
    return {"平均": float(sim.mean()), "中央値": float(np.median(sim)), "悪い年（下位5%）": float(np.quantile(sim, 0.05)),
            "目標に届かない確率": float((sim < target).mean())}


def expected_by_stream(streams: Sequence[tuple]) -> list[tuple[str, str, float]]:
    """天候が平年並みのときの、品目ごとの手取りの期待値（成り立つ確率をかける）"""
    return [(s[0], s[1], s[2] * s[3] * (1 - s[4]) * s[6]) for s in streams]


