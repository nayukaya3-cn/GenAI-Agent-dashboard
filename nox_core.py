    who, value, box, _, event, story = SCENES[scene]
    row = next(r for r in STORY if r[0] == month)
    return {"goal": f"農園の発信文（SNS）を書きたい。今月の話題は「{row[2]}」。",
            "context": f"畑では今「{row[1]}」をしている。届けたい人は{who}。届けたい価値観は「{value}」。物語の柱は「{story}」。",
            "rule": "150字以内。売り込みの言葉より、畑の様子が目に浮かぶ言葉で。値段・日付・人の名前は自分で入れるので書かない。",
            "form": f"案を3つ。最後に「{row[3]}」への一言の案内をつける。",
            "check": ""}


